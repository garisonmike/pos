class SaleSerializer(serializers.ModelSerializer):
    """A sale as the till and the receipt need it."""

    lines = SaleLineSerializer(many=True, read_only=True)
    payments = PaymentSerializer(many=True, read_only=True)
    refunds = RefundSerializer(many=True, read_only=True)

    cashier_name = serializers.CharField(source="cashier.full_name", read_only=True)
    store_code = serializers.CharField(source="store.code", read_only=True)
    amount_due_cents = serializers.IntegerField(read_only=True)
    change_cents = serializers.SerializerMethodField()

    class Meta:
        model = Sale
        fields = (
            "id",
            "client_uuid",
            "receipt_number",
            "receipt_code",
            "provisional_reference",
            "state",
            "store",
            "store_code",
            "cashier",
            "cashier_name",
            "subtotal_cents",
            "discount_cents",
            "tax_cents",
            "total_cents",
            "rounding_adjustment_cents",
            "amount_due_cents",
            "change_cents",
            "is_overpaid",
            "discount_authorized_label",
            "discount_authorization_reason",
            "discount_authorized_via",
            "discount_authorized_at",
            "customer_phone",
            "note",
            "was_offline",
            "device_created_at",
            "server_received_at",
            "created_at",
            "lines",
            "payments",
            "refunds",
        )
        read_only_fields = fields

    def get_change_cents(self, obj: Sale) -> int:
        """Change handed back, summed from the payments that gave it."""
        return sum(payment.change_cents for payment in obj.payments.all())
